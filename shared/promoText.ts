// Тексты промо-уведомления, общие для сайта и тестов.

/**
 * Код показывается в отдельной рамке с кнопкой «Копировать», поэтому из заголовка убираем повтор:
 * «Скидка 10% на первую покупку — промокод AMOR10» → «Скидка 10% на первую покупку».
 * Если в тексте такого оборота нет, он остаётся без изменений.
 */
export function titleWithoutCode(text: string, code: string): string {
  const escaped = code.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
  const cleaned = text
    .replace(new RegExp(`\\s*[—–-]?\\s*промокод\\s*:?\\s*${escaped}\\s*`, "i"), " ")
    .trim();
  return cleaned || text;
}
